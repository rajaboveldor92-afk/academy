# --- Ufq tomonlari: burilish savollari Python'da hisoblanadi.
_dirs = ["shimol", "sharq", "janub", "g‘arb"]  # soat mili bo'yicha
_dat = {"shimol": "shimolga", "sharq": "sharqqa", "janub": "janubga", "g‘arb": "g‘arbga"}
_turns = {"o‘ngga burilsangiz": 1, "chapga burilsangiz": -1, "orqaga o‘girilsangiz": 2, "ikki marta o‘ngga burilsangiz": 2}
_dirq = []
for start, turn, d in [("shimol", "o‘ngga burilsangiz", 2), ("sharq", "o‘ngga burilsangiz", 2), ("shimol", "chapga burilsangiz", 2),
                       ("janub", "chapga burilsangiz", 3), ("g‘arb", "orqaga o‘girilsangiz", 2), ("sharq", "ikki marta o‘ngga burilsangiz", 3)]:
    end = _dirs[(_dirs.index(start) + _turns[turn]) % 4]
    ans = _dat[end][0].upper() + _dat[end][1:]
